-- INAGRI: tablas de la base relacional (Amazon RDS for PostgreSQL).
-- Datos administrativos: productores, parcelas, sensores, cultivos, ciclos de siembra y usuarios.
-- Las lecturas de los sensores NO van aquí: viven en DynamoDB (llave id_sensor + fecha_hora).
--
-- Ejecutar con el usuario administrador, conectado a la base inagri:
--   psql -h <host> -U <usuario_admin> -d inagri -f sql/01_tablas.sql

CREATE TABLE IF NOT EXISTS productores (
    id_productor  INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    telefono      VARCHAR(20),
    correo        VARCHAR(100) UNIQUE,
    comunidad     VARCHAR(100),
    estatus       VARCHAR(10)  NOT NULL DEFAULT 'activo'
                  CHECK (estatus IN ('activo', 'inactivo')),
    fecha_alta    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS parcelas (
    id_parcela    INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_productor  INTEGER      NOT NULL REFERENCES productores (id_productor) ON DELETE RESTRICT,
    nombre        VARCHAR(100) NOT NULL,
    ubicacion     VARCHAR(150),
    superficie_ha NUMERIC(8, 2) NOT NULL CHECK (superficie_ha > 0),
    fecha_alta    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_parcelas_productor ON parcelas (id_productor);

-- Une cada sensor con su parcela. El id_sensor es el mismo que se usa en DynamoDB.
CREATE TABLE IF NOT EXISTS sensores (
    id_sensor     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parcela    INTEGER      NOT NULL REFERENCES parcelas (id_parcela) ON DELETE RESTRICT,
    descripcion   VARCHAR(100),
    estatus       VARCHAR(10)  NOT NULL DEFAULT 'activo'
                  CHECK (estatus IN ('activo', 'inactivo')),
    fecha_alta    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sensores_parcela ON sensores (id_parcela);

CREATE TABLE IF NOT EXISTS cultivos (
    id_cultivo    INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60)  NOT NULL UNIQUE,
    tipo          VARCHAR(40),
    duracion_dias INTEGER CHECK (duracion_dias > 0),
    -- Rango ideal del cultivo. Sirve para marcar la alerta "Requiere atención" en Mis parcelas.
    humedad_min   NUMERIC(5, 2) CHECK (humedad_min BETWEEN 0 AND 100),
    humedad_max   NUMERIC(5, 2) CHECK (humedad_max BETWEEN 0 AND 100),
    temp_min      NUMERIC(5, 2) CHECK (temp_min BETWEEN -40 AND 85),
    temp_max      NUMERIC(5, 2) CHECK (temp_max BETWEEN -40 AND 85),
    CHECK (humedad_min < humedad_max),
    CHECK (temp_min < temp_max)
);

CREATE TABLE IF NOT EXISTS ciclos_siembra (
    id_ciclo               INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_parcela             INTEGER     NOT NULL REFERENCES parcelas (id_parcela) ON DELETE RESTRICT,
    id_cultivo             INTEGER     NOT NULL REFERENCES cultivos (id_cultivo) ON DELETE RESTRICT,
    fecha_siembra          DATE        NOT NULL,
    fecha_cosecha_estimada DATE,
    estado                 VARCHAR(15) NOT NULL DEFAULT 'en_curso'
                           CHECK (estado IN ('planeado', 'en_curso', 'cosechado', 'cancelado')),
    CHECK (fecha_cosecha_estimada IS NULL OR fecha_cosecha_estimada > fecha_siembra)
);

CREATE INDEX IF NOT EXISTS idx_ciclos_parcela ON ciclos_siembra (id_parcela);

-- Cuentas de acceso. Se inicia sesión con el correo.
-- Un usuario con rol productor está ligado a su productor; si se elimina el productor,
-- se elimina también su cuenta.
CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario              INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(100) NOT NULL,
    correo                  VARCHAR(100) NOT NULL UNIQUE,
    hash_contrasena         VARCHAR(255) NOT NULL,
    rol                     VARCHAR(15)  NOT NULL CHECK (rol IN ('administrador', 'productor')),
    id_productor            INTEGER UNIQUE REFERENCES productores (id_productor) ON DELETE CASCADE,
    debe_cambiar_contrasena BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha_alta              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ultimo_acceso           TIMESTAMPTZ,
    CHECK ((rol = 'productor') = (id_productor IS NOT NULL))
);
